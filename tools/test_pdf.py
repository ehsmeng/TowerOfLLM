"""Tests for tools/pdf.py.  Run: python -m unittest tools.test_pdf"""

from __future__ import annotations

import tempfile
import unittest
from pathlib import Path

from tools.pdf import (BookError, build_model, compile_pdf, pick_book, review_flags, smart_quotes,
                       sort_key)
from tools.schema import load_config

REPO = Path(__file__).resolve().parent.parent
EXAMPLE = REPO / "docs" / "example" / "german"


class Helpers(unittest.TestCase):
    def test_review_flags_from_notes(self):
        notes = ("generated by claude-opus-5-5 (tools/generate.py, 2026-11-28) | "
                 "REVIEW warning: Explanation is vague. | REVIEW error: Wrong case.")
        self.assertEqual(review_flags(notes), ["Explanation is vague.", "(error) Wrong case."])
        self.assertEqual(review_flags("plain note"), [])
        self.assertEqual(review_flags(None), [])

    def test_smart_quotes(self):
        self.assertEqual(smart_quotes("'sein' isn't (\"du\")"), "‘sein’ isn’t (“du”)")
        self.assertEqual(smart_quotes("Wie geht's?"), "Wie geht’s?")

    def test_sort_key_folds_umlauts_and_punctuation(self):
        forms = ["über", "Sie", "uns", "sie", "'It's me'", "alle", "ärger"]
        self.assertEqual(sorted(forms, key=sort_key),
                         ["alle", "ärger", "'It's me'", "Sie", "sie", "über", "uns"])

    def test_pick_book(self):
        cfg = load_config(EXAMPLE)
        self.assertEqual(pick_book(cfg, None).id, "1-1000")
        with self.assertRaises(BookError):
            pick_book(cfg, "nope")


class Model(unittest.TestCase):
    def setUp(self):
        self.book = pick_book(load_config(EXAMPLE), None)

    def test_pilot_range(self):
        m = build_model(EXAMPLE, self.book, to=2)
        self.assertEqual([e["order"] for e in m["entries"]], [1, 2])
        self.assertTrue(m["book"]["pilot"])
        self.assertEqual(m["book"]["planned_last"], 1000)
        # every concept in range is placed on its first_entry page, numbered from 1
        placed = [c for e in m["entries"] for c in e["grammar"]]
        self.assertEqual([c["number"] for c in placed], list(range(1, len(placed) + 1)))
        for e in m["entries"]:
            for c in e["grammar"]:
                self.assertEqual(c["entry"], e["order"])

    def test_notes_never_in_model(self):
        m = build_model(EXAMPLE, self.book, to=2)
        def walk(o):
            if isinstance(o, dict):
                self.assertNotIn("notes", o)
                for v in o.values():
                    walk(v)
            elif isinstance(o, list):
                for v in o:
                    walk(v)
        walk(m["entries"])
        walk(m["appendix"])

    def test_missing_entries_fail_loud(self):
        with self.assertRaisesRegex(BookError, "entries missing"):
            build_model(EXAMPLE, self.book, to=3)

    def test_verb_rows_have_persons_and_examples(self):
        m = build_model(EXAMPLE, self.book, to=2)
        [sein] = m["appendix"]["verbs"]
        row = sein["tenses"][0]["forms"][0]
        self.assertEqual((row["person"], row["person_en"], row["form"]), ("ich", "I", "bin"))
        self.assertEqual(row["example"]["text"], "Ich bin müde.")
        imp = sein["tenses"][-1]["forms"]
        self.assertEqual([r["person_en"] for r in imp][-1], "you (formal)")

    def test_ahead_words_listed(self):
        import shutil
        from tools.schema import Entry, Sentence, dump_json, load_json
        with tempfile.TemporaryDirectory() as d:
            root = Path(d) / "german"
            shutil.copytree(EXAMPLE, root)
            p = root / "json" / "entries" / "00001 ich.json"
            e = load_json(Entry, p)
            e.meanings[0].sentences = [Sentence("Ich bin es.", "It's me.", ahead=True)]
            dump_json(e, p)
            m = build_model(root, self.book, to=2)
            [s_] = m["entries"][0]["meanings"][0]["sentences"]
            self.assertEqual(s_["ahead"], [{"form": "bin", "order": 2}, {"form": "es", "order": 12}])

    def test_compile(self):
        try:
            import typst  # noqa: F401
        except ImportError:
            self.skipTest("typst not installed")
        m = build_model(EXAMPLE, self.book, to=2)
        with tempfile.TemporaryDirectory() as d:
            out = Path(d) / "t.pdf"
            compile_pdf(m, out)
            self.assertTrue(out.read_bytes().startswith(b"%PDF"))


if __name__ == "__main__":
    unittest.main()
