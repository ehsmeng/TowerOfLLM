class GenSentence(BaseModel):
    text: str
    en: str
    grammar_notes: list[str]
    notes: Optional[str]


class GenMeaning(BaseModel):
    gloss: str
    base: str
    pos: POS
    morph: Optional[str]
    sentences: list[GenSentence]


class GenEntry(BaseModel):
    order: int
    form: str
    base: str
    translation: str
    meanings: list[GenMeaning]
    notes: Optional[str]


class GenExample(BaseModel):
    text: str
    en: str


class GenConcept(BaseModel):
    id: str
    title: str
    explanation: str
    first_entry: int
    related: list[str]
    examples: list[GenExample]


class GenBatch(BaseModel):
    entries: list[GenEntry]
    new_concepts: list[GenConcept]


class ReviewIssue(BaseModel):
    order: Optional[int]          # entry order, or null for a grammar concept
    meaning: Optional[int]        # 0-based meaning index, or null for entry-level
    sentence: Optional[int]       # 0-based sentence index, or null
    concept_id: Optional[str]     # grammar concept id, or null
    example: Optional[int]        # 0-based example index within the concept, or null
    severity: Literal["error", "warning"]
    issue: str


class Review(BaseModel):
    issues: list[ReviewIssue]


class GenAheadSentence(BaseModel):
    text: str
    en: str


class GenAheadItem(BaseModel):
    order: int                    # entry order
    meaning: int                  # 0-based meaning index
    sentences: list[GenAheadSentence]


class GenAhead(BaseModel):
    items: list[GenAheadItem]


