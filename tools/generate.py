def load_grammar(paths: LanguagePaths, code: str) -> Grammar:
    if paths.grammar.exists():
        return load_json(Grammar, paths.grammar)
    return Grammar(schema_version=SCHEMA_VERSION, language=code, concepts=[],
                   notes="Concepts in order of first_entry. Generated by tools/generate.py; "
                         "`review` fields and REVIEW notes come from the automatic reviewer pass.")


def existing_entries(paths: LanguagePaths) -> dict[int, tuple[Path, Entry]]:
    out = {}
    if paths.entries_dir.exists():
        for p in paths.entries_dir.glob("*.json"):
            e = load_json(Entry, p)
            out[e.order] = (p, e)
    return out


def clear_range(paths: LanguagePaths, code: str, lo: int, hi: int) -> None:
    """--force: delete entries and grammar concepts in [lo, hi] before
    regenerating. Entries after hi were written against the old grammar
    (first-use, ids), so they must be regenerated too; refuse rather than
    leave a course that silently mixes the two."""
    have = existing_entries(paths)
    later = sorted(n for n in have if n > hi)
    if later:
        sys.exit(f"--force {lo}..{hi}: entries {later[0]}..{later[-1]} exist after the range and "
                 f"depend on its grammar; use --to {later[-1]} to regenerate them too")
    for n, (p, _) in have.items():
        if n >= lo:
            p.unlink()
    if paths.grammar.exists():
        g = load_json(Grammar, paths.grammar)
        g.concepts = [c for c in g.concepts if c.first_entry < lo]
        dump_json(g, paths.grammar)
    print(f"--force: cleared entries and concepts {lo}..{hi}", file=sys.stderr)


def run(root: Path, lo: int, hi: int, batch_size: int, model: str, effort: str,
        retries: int, review: bool, force: bool, ahead: bool = True) -> int:
    cfg = load_config(root)
    paths = LanguagePaths(root)
    words = load_json(WordList, paths.words)
    lang = load_language_module(root)
    vocab = Vocabulary(words, _names(lang))
    places = SUGGESTED_PLACES.get(cfg.code, "")
    people = [f for f, cat in getattr(lang, "NAMES", {}).items()
              if cat == "person" and f not in NOT_CAST.get(cfg.code, set())]
    system = SYSTEM.format(name=cfg.name, places=places,
                           per_meaning=MAX_SENTENCES_PER_MEANING,
                           per_entry=MAX_SENTENCES_PER_ENTRY, max_ex=MAX_GRAMMAR_EXAMPLES)
    review_system = REVIEW_SYSTEM.format(name=cfg.name)
    a_system = ahead_system(cfg, words, places)
    stamp = dt.datetime.now().strftime("%Y%m%d-%H%M%S")
    gen = Generator(model, effort, REPO / "cache" / "generate" / f"{root.name}-{stamp}-{model}.jsonl")
    print(f"{root}: entries {lo}..{hi}, model {model}, effort {effort}, log {gen.log_path}",
          file=sys.stderr)

    if force:
        clear_range(paths, cfg.code, lo, hi)

    all_dropped: list[str] = []
    for b_lo in range(lo, hi + 1, batch_size):
        b_hi = min(b_lo + batch_size - 1, hi)
        have = existing_entries(paths)
        if not force and all(n in have for n in range(b_lo, b_hi + 1)):
            print(f"batch {b_lo}-{b_hi}: exists, skipping", file=sys.stderr)
            continue
        print(f"batch {b_lo}-{b_hi}:", file=sys.stderr)
        gen.served.clear()

        grammar = load_grammar(paths, cfg.code)
        prior = [c for c in grammar.concepts if c.first_entry < b_lo]
        anchor = [e for n, (_, e) in sorted(have.items()) if b_lo - batch_size <= n < b_lo]

        base_prompt = batch_prompt(words, b_lo, b_hi, prior, anchor,
                                   batch_people(cfg.code, b_lo, people))
        batch = gen.call(system, base_prompt, GenBatch, f"{b_lo}-{b_hi} attempt 1")
        problems = check_batch(batch, b_lo, b_hi, words, vocab, prior, lang, cfg.code)
        for attempt in range(2, retries + 2):
            if not problems:
                break
            print(f"    {len(problems.messages)} problem(s), retrying", file=sys.stderr)
            batch = gen.call(system, base_prompt + "\n\n" + retry_prompt(batch, problems.messages),
                             GenBatch, f"{b_lo}-{b_hi} attempt {attempt}")
            problems = check_batch(batch, b_lo, b_hi, words, vocab, prior, lang, cfg.code)
        if problems:
            if any("entries must be exactly" in f for f in problems.fatal):
                gen.log(label=f"{b_lo}-{b_hi} fatal", problems=problems.messages)
                sys.exit(f"batch {b_lo}-{b_hi}: model kept returning the wrong entries; aborting")
            batch, dropped = drop_failing(batch, problems, prior)
            leftover = check_batch(batch, b_lo, b_hi, words, vocab, prior, lang, cfg.code)
            if leftover:
                gen.log(label=f"{b_lo}-{b_hi} unfixable", problems=leftover.messages)
                sys.exit(f"batch {b_lo}-{b_hi}: still failing after drops:\n  "
                         + "\n  ".join(leftover.messages))
            all_dropped += dropped
            gen.log(label=f"{b_lo}-{b_hi} dropped", dropped=dropped)
            for d in dropped:
                print(f"    DROPPED {d}", file=sys.stderr)

        entries = [to_entry(e, cfg.code) for e in batch.entries]
        concepts = [to_concept(c) for c in batch.new_concepts]
        stamp_note = (f"{PROVENANCE_PREFIX}{', '.join(sorted(gen.served))} "
                      f"(tools/generate.py, {dt.date.today().isoformat()})")
        for obj in [*entries, *concepts]:
            obj.notes = _append_note(stamp_note, obj.notes) if obj.notes else stamp_note

        if ahead:
            _, dropped = fill_ahead(gen, a_system, entries, vocab, lang, len(words.words), retries,
                                    batch_people(cfg.code, b_lo, people), f"{b_lo}-{b_hi}")
            all_dropped += dropped

        if review:
            listing = {"entries": [_entry_dict(e) for e in entries],
                       "new_concepts": [c.model_dump() for c in batch.new_concepts]}
            rev = gen.call(review_system,
                           f"Known vocabulary (order<TAB>form):\n{vocab_block(words, b_hi)}\n\n"
                           f"CONTENT TO REVIEW:\n{json.dumps(listing, ensure_ascii=False)}",
                           Review, f"{b_lo}-{b_hi} review")
            unplaced = apply_review(entries, concepts, rev)
            n_err = sum(i.severity == "error" for i in rev.issues)
            print(f"    review: {n_err} error(s), {len(rev.issues) - n_err} warning(s)"
                  + (f", {len(unplaced)} unplaced" if unplaced else ""), file=sys.stderr)
            if unplaced:
                gen.log(label=f"{b_lo}-{b_hi} review unplaced", issues=unplaced)

        # Write: replace this range's entries and concepts.
        for n in range(b_lo, b_hi + 1):
            if n in have:
                have[n][0].unlink()
        for e in entries:
            dump_json(e, paths.entry(e.order, e.form))
        grammar.concepts = ([c for c in grammar.concepts if not b_lo <= c.first_entry <= b_hi]
                            + concepts)
        grammar.concepts.sort(key=lambda c: c.first_entry)
        dump_json(grammar, paths.grammar)

        errs = check_language(root, 1, b_hi)
        if errs:
            for e in errs:
                print(f"    CHECKER {e}", file=sys.stderr)
            sys.exit(f"batch {b_lo}-{b_hi}: sentence checker failed after writing (bug in "
                     f"generate.py's in-process checks)")
        n_sent = sum(len(m.sentences) for e in entries for m in e.meanings)
        print(f"    wrote {len(entries)} entries, {n_sent} sentences, {len(concepts)} new "
              f"concept(s); running cost ${gen.usage.cost(model):.2f}", file=sys.stderr)

    print(f"done. usage: {gen.usage}; est. cost ${gen.usage.cost(model):.2f}; "
          f"{len(all_dropped)} item(s) dropped", file=sys.stderr)
    return 0


def run_fill_ahead(root: Path, lo: int, hi: int, batch_size: int, model: str, effort: str,
                   retries: int, review: bool) -> int:
    """--fill-ahead: add ahead sentences to existing entries in [lo, hi]."""
    cfg = load_config(root)
    paths = LanguagePaths(root)
    words = load_json(WordList, paths.words)
    lang = load_language_module(root)
    vocab = Vocabulary(words, _names(lang))
    places = SUGGESTED_PLACES.get(cfg.code, "")
    people = [f for f, cat in getattr(lang, "NAMES", {}).items()
              if cat == "person" and f not in NOT_CAST.get(cfg.code, set())]
    a_system = ahead_system(cfg, words, places)
    review_system = REVIEW_SYSTEM.format(name=cfg.name)
    stamp = dt.datetime.now().strftime("%Y%m%d-%H%M%S")
    gen = Generator(model, effort, REPO / "cache" / "generate" / f"{root.name}-{stamp}-{model}-ahead.jsonl")
    have = existing_entries(paths)
    missing = [n for n in range(lo, hi + 1) if n not in have]
    if missing:
        sys.exit(f"--fill-ahead: entries {missing[:5]}... missing; generate them first")
    print(f"{root}: ahead pass {lo}..{hi}, model {model}, log {gen.log_path}", file=sys.stderr)
    all_dropped: list[str] = []
    for b_lo in range(lo, hi + 1, batch_size):
        b_hi = min(b_lo + batch_size - 1, hi)
        entries = [have[n][1] for n in range(b_lo, b_hi + 1)]
        if not empty_meanings(entries):
            continue
        print(f"batch {b_lo}-{b_hi}:", file=sys.stderr)
        gen.served.clear()
        filled, dropped = fill_ahead(gen, a_system, entries, vocab, lang, len(words.words), retries,
                                     batch_people(cfg.code, b_lo, people), f"{b_lo}-{b_hi}")
        all_dropped += dropped
        if review and filled:
            touched = [e for e in entries if any(o == e.order for o, _ in filled)]
            rev = gen.call(review_system,
                           f"Known vocabulary (order<TAB>form):\n{vocab_block(words, b_hi)}\n\n"
                           "Review ONLY the sentences marked \"ahead\": true (they are new); "
                           "everything else was reviewed before. Locate issues with order/"
                           "meaning/sentence as usual.\n\n"
                           f"CONTENT TO REVIEW:\n{json.dumps({'entries': [_entry_dict(e) for e in touched], 'new_concepts': []}, ensure_ascii=False)}",
                           Review, f"{b_lo}-{b_hi} ahead review")
            fset = set(filled)
            rev.issues = [i for i in rev.issues
                          if i.order is not None and (i.order, i.meaning) in fset and i.sentence is not None]
            unplaced = apply_review(touched, [], rev)
            print(f"    review: {len(rev.issues)} remark(s)" + (f", {len(unplaced)} unplaced" if unplaced else ""),
                  file=sys.stderr)
        for e in entries:
            if any(o == e.order for o, _ in filled):
                dump_json(e, have[e.order][0])
        errs = check_language(root, 1, b_hi)
        if errs:
            for x in errs:
                print(f"    CHECKER {x}", file=sys.stderr)
            sys.exit(f"batch {b_lo}-{b_hi}: sentence checker failed after the ahead pass")
    print(f"done. usage: {gen.usage}; est. cost ${gen.usage.cost(model):.2f}; "
          f"{len(all_dropped)} item(s) dropped", file=sys.stderr)
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="python -m tools.generate", description=__doc__.split("\n\n")[0])
    ap.add_argument("lang", type=Path, help="language directory, e.g. german")
    ap.add_argument("--from", dest="lo", type=int, default=1)
    ap.add_argument("--to", dest="hi", type=int, required=True)
    ap.add_argument("--batch", type=int, default=10, help="entries per API call (default 10)")
    ap.add_argument("--model", default=DEFAULT_MODEL, choices=sorted(PRICES))
    ap.add_argument("--effort", default="high", choices=["low", "medium", "high", "xhigh", "max"])
    ap.add_argument("--retries", type=int, default=3, help="retry rounds per batch (default 3)")
    ap.add_argument("--no-review", dest="review", action="store_false")
    ap.add_argument("--force", action="store_true", help="regenerate batches that already exist")
    ap.add_argument("--no-ahead", dest="ahead", action="store_false",
                    help="leave meanings without sentences empty (no ahead pass)")
    ap.add_argument("--fill-ahead", action="store_true",
                    help="only run the ahead pass on existing entries in the range")
    a = ap.parse_args(argv)
    if a.fill_ahead:
        return run_fill_ahead(a.lang, a.lo, a.hi, a.batch, a.model, a.effort, a.retries, a.review)
    if a.lo != 1 and not existing_entries(LanguagePaths(a.lang)).get(a.lo - 1):
        sys.exit(f"entry {a.lo - 1} missing: generate in order so grammar first-use is known")
    return run(a.lang, a.lo, a.hi, a.batch, a.model, a.effort, a.retries, a.review, a.force, a.ahead)


if __name__ == "__main__":
    sys.exit(main())
