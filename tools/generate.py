def _entry_dict(e: Entry) -> dict:
    from tools.schema import to_dict
    return to_dict(e)


def to_entry(g: GenEntry, code: str) -> Entry:
    d = g.model_dump(exclude_none=True)
    d = {"schema_version": SCHEMA_VERSION, "language": code, **d}
    return from_dict(Entry, d)


def to_concept(g: GenConcept) -> GrammarConcept:
    return from_dict(GrammarConcept, g.model_dump(exclude_none=True))


def _append_note(old: str | None, new: str) -> str:
    return f"{old} | {new}" if old else new


def _append_review(old: str | None, new: str) -> str:
    return f"{old} {new}" if old else new


def apply_review(entries: list[Entry], concepts: list[GrammarConcept], review: Review) -> list[str]:
    by_order = {e.order: e for e in entries}
    by_id = {c.id: c for c in concepts}
    unplaced = []
    for it in review.issues:
        note = f"REVIEW {it.severity}: {it.issue}"
        try:
            if it.concept_id is not None:
                c = by_id[it.concept_id]
                if it.example is not None:
                    ex = c.examples[it.example]
                    ex.review = _append_review(ex.review, it.issue)
                else:
                    c.notes = _append_note(c.notes, note)
            elif it.order is not None:
                e = by_order[it.order]
                if it.meaning is None:
                    e.notes = _append_note(e.notes, note)
                elif it.sentence is None:
                    m = e.meanings[it.meaning]
                    m.notes = _append_note(m.notes, note)
                else:
                    s = e.meanings[it.meaning].sentences[it.sentence]
                    s.review = _append_review(s.review, it.issue)
            else:
                raise KeyError("no location")
        except (KeyError, IndexError):
            unplaced.append(f"{it.model_dump_json()}")
    return unplaced


