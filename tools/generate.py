@dataclass
class Problems:
    """Violations found in a batch. `bad_sentences` / `bad_examples` are
    removable; `fatal` ones (wrong entries returned) can't be dropped."""
    messages: list[str] = field(default_factory=list)
    bad_sentences: set[tuple[int, int, int]] = field(default_factory=set)  # (order, meaning, sentence)
    bad_examples: set[tuple[str, int]] = field(default_factory=set)        # (concept id, example)
    bad_concepts: set[str] = field(default_factory=set)
    fatal: list[str] = field(default_factory=list)

    def __bool__(self) -> bool:
        return bool(self.messages or self.fatal)


def uses_form(text: str, form: str, lang) -> bool:
    for tok in tokenize(text, lang):
        t = tok.text
        if t == form or (tok.ambiguous and t[:1].isupper() and t[:1].lower() + t[1:] == form):
            return True
    return False


def check_batch(batch: GenBatch, lo: int, hi: int, words: WordList, vocab: Vocabulary,
                existing: list[GrammarConcept], lang, code: str) -> Problems:
    p = Problems()
    want = [(w.order, w.form) for w in words.words if lo <= w.order <= hi]
    got = [(e.order, e.form) for e in batch.entries]
    if got != want:
        p.fatal.append(f"entries must be exactly {want}, got {got}")
        p.messages.append(p.fatal[-1])
        return p

    existing_ids = {c.id for c in existing}
    new = {c.id: c for c in batch.new_concepts}
    intro: dict[str, list[tuple[int, int, int]]] = {}

    for e in batch.entries:
        ent = to_entry(e, code)
        for err in validate_entry(ent, f"entry {e.order}"):
            p.messages.append(err)
        if sum(len(m.sentences) for m in e.meanings) > MAX_SENTENCES_PER_ENTRY:
            p.fatal.append(f"entry {e.order}: more than {MAX_SENTENCES_PER_ENTRY} sentences")
        for i, m in enumerate(e.meanings):
            if len(m.sentences) > MAX_SENTENCES_PER_MEANING:
                p.fatal.append(f"entry {e.order} meaning {i}: more than {MAX_SENTENCES_PER_MEANING} sentences")
            for j, s in enumerate(m.sentences):
                key = (e.order, i, j)
                loc = f"entry {e.order} ({e.form}) meaning {i} sentence {j} {s.text!r}"
                for v in vocab.check(s.text, e.order, loc, lang):
                    p.messages.append(f"{loc}: {v.token!r} {v.reason}")
                    p.bad_sentences.add(key)
                if not uses_form(s.text, e.form, lang):
                    p.messages.append(f"{loc}: does not use the taught form {e.form!r}")
                    p.bad_sentences.add(key)
                for g in s.grammar_notes:
                    intro.setdefault(g, []).append(key)
                    if g in existing_ids:
                        p.messages.append(f"{loc}: grammar note '{g}' was already introduced "
                                          f"earlier; remove it from grammar_notes")
                        p.bad_sentences.add(key)
                    elif g not in new:
                        p.messages.append(f"{loc}: grammar note '{g}' is not defined in new_concepts")
                        p.bad_sentences.add(key)
    # Over-limit counts are trimmed by drop_failing if retries don't fix them.
    p.messages += [f for f in p.fatal if f not in p.messages]

    all_ids = existing_ids | set(new)
    for c in batch.new_concepts:
        cw = f"grammar '{c.id}'"
        if not GRAMMAR_ID_RE.match(c.id):
            p.messages.append(f"{cw}: bad id (dotted lowercase a-z0-9_)")
            p.bad_concepts.add(c.id)
        if c.id in existing_ids:
            p.messages.append(f"{cw}: already exists; do not redefine it")
            p.bad_concepts.add(c.id)
        sites = intro.get(c.id, [])
        if len(sites) != 1:
            p.messages.append(f"{cw}: introduced in {len(sites)} sentences {sites}; must be exactly one")
            p.bad_concepts.add(c.id)
        elif sites[0][0] != c.first_entry:
            p.messages.append(f"{cw}: first_entry {c.first_entry} but introduced in entry {sites[0][0]}")
            p.bad_concepts.add(c.id)
        for r in c.related:
            if r not in all_ids:
                p.messages.append(f"{cw}: related id '{r}' does not exist")
        if len(c.examples) > MAX_GRAMMAR_EXAMPLES:
            p.messages.append(f"{cw}: {len(c.examples)} examples > {MAX_GRAMMAR_EXAMPLES}")
        for j, ex in enumerate(c.examples):
            loc = f"{cw} (first_entry {c.first_entry}) example {j} {ex.text!r}"
            for v in vocab.check(ex.text, c.first_entry, loc, lang):
                p.messages.append(f"{loc}: {v.token!r} {v.reason}")
                p.bad_examples.add((c.id, j))
    return p


def drop_failing(batch: GenBatch, p: Problems, existing: list[GrammarConcept]) -> tuple[GenBatch, list[str]]:
    """Remove what still fails after the last retry. Returns the cleaned batch
    and a human-readable list of what was dropped."""
    dropped: list[str] = []
    b = batch.model_copy(deep=True)
    existing_ids = {c.id for c in existing}

    for e in b.entries:
        for i, m in enumerate(e.meanings):
            keep = []
            for j, s in enumerate(m.sentences):
                if (e.order, i, j) in p.bad_sentences:
                    dropped.append(f"entry {e.order} ({e.form}) sentence {s.text!r}")
                else:
                    keep.append(s)
            m.sentences = keep[:MAX_SENTENCES_PER_MEANING]
        # entry total limit: trim the longest meanings first
        while sum(len(m.sentences) for m in e.meanings) > MAX_SENTENCES_PER_ENTRY:
            longest = max(e.meanings, key=lambda m: len(m.sentences))
            s = longest.sentences.pop()
            dropped.append(f"entry {e.order} ({e.form}) sentence {s.text!r} (over entry limit)")

    # Concepts: drop the bad ones, then any whose introducing sentence is gone.
    intro: dict[str, list[GenSentence]] = {}
    for e in b.entries:
        for m in e.meanings:
            for s in m.sentences:
                for g in s.grammar_notes:
                    intro.setdefault(g, []).append(s)
    concepts = []
    for c in b.new_concepts:
        if c.id in p.bad_concepts or c.id in existing_ids or not intro.get(c.id):
            dropped.append(f"grammar concept '{c.id}'")
            continue
        exs = [ex for j, ex in enumerate(c.examples) if (c.id, j) not in p.bad_examples]
        for j, ex in enumerate(c.examples):
            if (c.id, j) in p.bad_examples:
                dropped.append(f"grammar '{c.id}' example {ex.text!r}")
        c.examples = exs[:MAX_GRAMMAR_EXAMPLES]
        concepts.append(c)
    b.new_concepts = concepts
    keep_ids = existing_ids | {c.id for c in concepts}
    # Strip dangling notes; keep only the first introduction of each concept.
    seen: set[str] = set()
    for e in b.entries:
        for m in e.meanings:
            for s in m.sentences:
                notes = []
                for g in s.grammar_notes:
                    if g in keep_ids and g not in existing_ids and g not in seen:
                        notes.append(g)
                        seen.add(g)
                s.grammar_notes = notes
    for c in b.new_concepts:
        c.related = [r for r in c.related if r in keep_ids]
    return b, dropped


