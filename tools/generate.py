@dataclass
class Usage:
    input: int = 0
    output: int = 0
    cache_read: int = 0
    cache_write: int = 0

    def add(self, u) -> None:
        self.input += u.input_tokens or 0
        self.output += u.output_tokens or 0
        self.cache_read += getattr(u, "cache_read_input_tokens", 0) or 0
        self.cache_write += getattr(u, "cache_creation_input_tokens", 0) or 0

    def cost(self, model: str) -> float:
        pi, po, pc = PRICES.get(model, (0.0, 0.0, 0.0))
        return (self.input * pi + self.cache_write * pi * 1.25
                + self.cache_read * pc + self.output * po) / 1e6

    def __str__(self) -> str:
        return (f"in {self.input} (+{self.cache_read} cached, +{self.cache_write} cache-write), "
                f"out {self.output}")


class Generator:
    def __init__(self, model: str, effort: str, log_path: Path):
        key = os.environ.get(KEY_ENV)
        if not key:
            sys.exit(f"error: ${KEY_ENV} is not set (the ticket secret); refusing to "
                     f"fall back to ANTHROPIC_API_KEY")
        self.client = anthropic.Anthropic(api_key=key)
        self.model = model
        self.effort = effort
        self.usage = Usage()
        self.served: set[str] = set()   # models that actually answered (fallbacks may differ)
        self.log_path = log_path
        log_path.parent.mkdir(parents=True, exist_ok=True)

    def log(self, **rec) -> None:
        rec["ts"] = dt.datetime.now().isoformat(timespec="seconds")
        with self.log_path.open("a", encoding="utf-8") as fh:
            fh.write(json.dumps(rec, ensure_ascii=False) + "\n")

    def call(self, system: str, user: str, schema: type[BaseModel], label: str) -> BaseModel:
        t0 = time.time()
        with self.client.beta.messages.stream(
            model=self.model,
            max_tokens=64000,
            betas=[FALLBACK_BETA],
            fallbacks="default",
            thinking={"type": "adaptive"},
            output_config={"effort": self.effort},
            system=[{"type": "text", "text": system, "cache_control": {"type": "ephemeral"}}],
            messages=[{"role": "user", "content": user}],
            output_format=schema,
        ) as stream:
            msg = stream.get_final_message()
        u = Usage()
        u.add(msg.usage)
        self.usage.add(msg.usage)
        if schema is GenBatch or schema is GenAhead:
            self.served.add(msg.model)
        text = "".join(b.text for b in msg.content if b.type == "text")
        self.log(label=label, model=msg.model, stop_reason=msg.stop_reason,
                 usage=str(u), seconds=round(time.time() - t0, 1), prompt=user, response=text)
        if msg.stop_reason == "refusal":
            raise RuntimeError(f"{label}: model refused ({getattr(msg, 'stop_details', None)})")
        if msg.stop_reason == "max_tokens":
            raise RuntimeError(f"{label}: hit max_tokens")
        print(f"  {label}: {u}, {time.time() - t0:.0f}s"
              + (f" [served by {msg.model}]" if msg.model != self.model else ""), file=sys.stderr)
        return schema.model_validate_json(text)


