"""Render a language's course book to PDF with Typst.

Python loads and checks the JSON data, flattens it into one book model
(``cache/pdf/<lang>-<book>.json``), and ``tools/book.typ`` lays it out. The
template is language-neutral: every name, title and path comes from
``<lang>/language.toml`` (see ``[[books]]``) or from the data itself.

    python -m tools.pdf german                    # first book in language.toml
    python -m tools.pdf german --book 1-1000      # a named book
    python -m tools.pdf german --to 100           # pilot: cut the range at 100
    python -m tools.pdf german --to 100 --out x.pdf

What is printed:
- every sentence and grammar example with its translation, plus its `review`
  comment right after it (not in the verb appendix: verb reviews are acted on
  by ``tools.verbs`` and never printed);
- reviewer flags that only exist in `notes` (entry, meaning and concept level,
  marked ``REVIEW <severity>: ...``), printed the same way;
- each grammar concept once, on the page of its `first_entry`;
- under an `ahead` sentence, the forms it borrows from later in the course,
  with their learning numbers (computed by ``tools.checker.Vocabulary.later``);
- `notes` text is otherwise never printed.

Problems that make the book wrong (missing entries, a concept introduced
outside the range it is referenced from) fail loud; softer inconsistencies are
printed as warnings and also listed in the book model's ``warnings``.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import unicodedata
from dataclasses import dataclass, field
from datetime import date
from pathlib import Path

from tools.checker import Vocabulary, _names
from tools.frequency import load_language_module
from tools.schema import (Book, Entry, Grammar, GrammarConcept, LanguageConfig, LanguagePaths,
                          SchemaError, Verbs, WordList, load_config, load_json)

REPO = Path(__file__).resolve().parent.parent
TEMPLATE = Path(__file__).resolve().parent / "book.typ"
FONTS = REPO / "fonts"
CACHE = REPO / "cache" / "pdf"
APPENDIX_VERBS = 20

REVIEW_RE = re.compile(r"^REVIEW\s+(\w+)\s*:\s*(.+)$", re.S)
MODEL_RE = re.compile(r"generated by ([\w.\-]+)")


class BookError(RuntimeError):
    pass


# ---------------------------------------------------------------------------
# Small helpers
# ---------------------------------------------------------------------------


def review_flags(notes: str | None) -> list[str]:
    """Reviewer flags hidden in a `notes` string ('... | REVIEW warning: text | ...')."""
    if not notes:
        return []
    out = []
    for part in notes.split(" | "):
        m = REVIEW_RE.match(part.strip())
        if m:
            sev, text = m.group(1).lower(), m.group(2).strip()
            out.append(text if sev == "warning" else f"({sev}) {text}")
    return out


SMART_KEYS = {"text", "en", "review", "explanation", "title", "subtitle", "gloss",
              "translation", "morph", "label"}
OPEN_CTX = r"(^|[\s(\[{\u2014\u2013/-])"


def smart_quotes(s: str) -> str:
    """Straight quotes -> typographic: 'x' -> \u2018x\u2019, isn't -> isn\u2019t, "x" -> \u201cx\u201d."""
    s = re.sub(OPEN_CTX + "'", "\\1\u2018", s).replace("'", "\u2019")
    s = re.sub(OPEN_CTX + '"', "\\1\u201c", s).replace('"', "\u201d")
    return s


def typeset_strings(obj, key: str | None = None):
    """Apply smart_quotes to the display strings of the book model (not ids or paths)."""
    if isinstance(obj, dict):
        return {k: typeset_strings(v, k) for k, v in obj.items()}
    if isinstance(obj, list):
        return [typeset_strings(v, key) for v in obj]
    if isinstance(obj, str) and key in SMART_KEYS:
        return smart_quotes(obj)
    return obj


def sort_key(form: str) -> tuple[str, str]:
    """Alphabetical index key: punctuation dropped, diacritics folded (ä→a, ß→ss), then exact form."""
    folded = unicodedata.normalize("NFD", form.replace("ß", "ss"))
    folded = "".join(c for c in folded if not unicodedata.combining(c))
    letters = "".join(c for c in folded if c.isalnum() or c == " ").strip()
    return (letters.casefold(), form)


def pick_book(cfg: LanguageConfig, book_id: str | None) -> Book:
    if not cfg.books:
        raise BookError("language.toml has no [[books]] table")
    if book_id is None:
        return cfg.books[0]
    for b in cfg.books:
        if b.id == book_id:
            return b
    raise BookError(f"no book '{book_id}' in language.toml (have: {', '.join(b.id for b in cfg.books)})")


# ---------------------------------------------------------------------------
# Book model
# ---------------------------------------------------------------------------


@dataclass
class Model:
    warnings: list[str] = field(default_factory=list)

    def warn(self, msg: str) -> None:
        self.warnings.append(msg)


def _example(text: str, en: str, review: str | None) -> dict:
    return {"text": text, "en": en, "review": [review] if review else []}


def verb_row(person: str, form: str, tense, persons: dict[str, str]) -> dict:
    ex = tense.examples.get(person)
    return {"person": person, "person_en": persons.get(person), "form": form,
            "example": {"text": ex.text, "en": ex.en} if ex else None}  # verb reviews are acted on, never printed


def build_model(root: Path, book: Book, to: int | None = None) -> dict:
    """Load, check and flatten everything the template needs into plain JSON."""
    paths = LanguagePaths(root)
    cfg = load_config(root)
    words = load_json(WordList, paths.words)
    grammar = load_json(Grammar, paths.grammar)
    lang = load_language_module(root) if (root / "wordlist.py").exists() else None
    vocab = Vocabulary(words, _names(lang))
    m = Model()

    first = book.first
    last = min(book.last, to) if to else book.last
    if last < first:
        raise BookError(f"range {first}-{last} is empty")
    pilot = last < book.last

    by_order = {w.order: w for w in words.words}
    entries: list[Entry] = []
    missing = []
    for n in range(first, last + 1):
        w = by_order.get(n)
        if w is None:
            raise BookError(f"words.json has no order {n}")
        p = paths.entry(n, w.form)
        if not p.exists():
            missing.append(p.name)
            continue
        entries.append(load_json(Entry, p))
    if missing:
        more = f" (+{len(missing) - 5} more)" if len(missing) > 5 else ""
        raise BookError(f"{len(missing)} entries missing in {first}-{last}: "
                        f"{', '.join(missing[:5])}{more}. Use --to to render a shorter range.")

    # --- grammar: number concepts introduced in range, check references ---
    concepts: dict[str, GrammarConcept] = {c.id: c for c in grammar.concepts}
    in_range = [c for c in grammar.concepts if first <= c.first_entry <= last]
    in_range.sort(key=lambda c: (c.first_entry, grammar.concepts.index(c)))
    number = {c.id: i for i, c in enumerate(in_range, 1)}
    tagged_at: dict[str, list[int]] = {}
    for e in entries:
        for mn in e.meanings:
            for s in mn.sentences:
                for g in s.grammar_notes:
                    if g not in concepts:
                        raise BookError(f"entry {e.order} '{e.form}': unknown grammar id '{g}'")
                    tagged_at.setdefault(g, []).append(e.order)
    for c in in_range:
        at = tagged_at.get(c.id, [])
        if not at:
            m.warn(f"§{number[c.id]} {c.id}: introduced on {c.first_entry} but no sentence carries it")
        elif c.first_entry not in at:
            m.warn(f"§{number[c.id]} {c.id}: first_entry {c.first_entry}, but tagged on {sorted(set(at))}")
    for g, at in tagged_at.items():
        c = concepts[g]
        if c.first_entry < first and min(at) >= first:
            pass  # introduced in an earlier book: fine, rendered as a plain reference
        elif c.first_entry > last:
            m.warn(f"{g}: tagged on {sorted(set(at))} but first_entry {c.first_entry} is after this range")

    def concept_ref(cid: str) -> dict:
        c = concepts.get(cid)
        if c is None:
            m.warn(f"related id '{cid}' not in grammar.json")
            return {"id": cid, "title": cid, "number": None, "entry": None}
        return {"id": cid, "title": c.title, "number": number.get(cid),
                "entry": c.first_entry if first <= c.first_entry <= last else None}

    def concept_model(c: GrammarConcept) -> dict:
        return {
            "id": c.id, "number": number[c.id], "title": c.title,
            "explanation": c.explanation, "entry": c.first_entry,
            "examples": [_example(x.text, x.en, x.review) for x in c.examples],
            "related": [concept_ref(r) for r in c.related],
            "review": review_flags(c.notes),
        }

    # --- entries ---
    by_entry: dict[int, list[dict]] = {}
    for c in in_range:
        by_entry.setdefault(c.first_entry, []).append(concept_model(c))

    models: set[str] = set()
    out_entries = []
    n_sent = n_rev = n_ahead = 0
    for e in entries:
        sent_notes = [s.notes for mn in e.meanings for s in mn.sentences]
        for notes in [e.notes] + [mn.notes for mn in e.meanings] + sent_notes:
            models.update(MODEL_RE.findall(notes or ""))
        w = by_order[e.order]
        meanings = []
        for mn in e.meanings:
            sents = []
            for s in mn.sentences:
                later = [{"form": f, "order": o} for f, o in vocab.later(s.text, e.order, lang)]
                if s.ahead and not later:
                    m.warn(f"entry {e.order} '{e.form}': ahead sentence {s.text!r} uses no later word")
                n_ahead += s.ahead
                sents.append({
                    "text": s.text, "en": s.en,
                    "grammar": [number[g] for g in s.grammar_notes if g in number],
                    "review": [s.review] if s.review else [],
                    "ahead": later if s.ahead else [],
                })
                n_sent += 1
                n_rev += bool(s.review)
            if not sents:
                m.warn(f"entry {e.order} '{e.form}' meaning '{mn.gloss}': no sentences "
                       f"(run tools.generate --fill-ahead)")
            meanings.append({"gloss": mn.gloss, "base": mn.base, "pos": mn.pos,
                             "morph": mn.morph, "sentences": sents,
                             "review": review_flags(mn.notes)})
        out_entries.append({
            "order": e.order, "form": e.form, "base": e.base, "translation": e.translation,
            "frequency_rank": w.frequency_rank, "count": f"{w.count:,}",
            "review": review_flags(e.notes), "meanings": meanings,
            "grammar": by_entry.get(e.order, []),
        })

    # --- appendix: verbs ---
    verbs_path, illustrative = paths.verbs, False
    if not verbs_path.exists():
        example = REPO / "docs" / "example" / root.name / "json" / "verbs.json"
        if not example.exists():
            raise BookError(f"{verbs_path} missing and no illustrative copy at {example}")
        m.warn(f"{verbs_path.relative_to(REPO)} missing: appendix uses illustrative "
               f"{example.relative_to(REPO)}")
        verbs_path, illustrative = example, True
    verbs = load_json(Verbs, verbs_path)
    top = sorted(verbs.verbs, key=lambda v: -v.total_count)[:APPENDIX_VERBS]
    appendix = {
        "illustrative": illustrative, "wanted": APPENDIX_VERBS,
        "verbs": [{"base": v.base, "translation": v.translation, "participles": v.participles,
                   "tenses": [{"label": t.label, "forms": [verb_row(k, f, t, verbs.persons)
                                                             for k, f in t.forms.items()]}
                              for t in v.tenses]} for v in top],
    }

    index = sorted(({"form": e.form, "order": e.order, "translation": e.translation}
                    for e in entries), key=lambda x: sort_key(x["form"]))
    gindex = sorted(({"title": c.title, "number": number[c.id], "entry": c.first_entry}
                     for c in in_range), key=lambda x: sort_key(x["title"]))

    for w_ in m.warnings:
        print(f"warning: {w_}", file=sys.stderr)

    return typeset_strings({
        "language": {"code": cfg.code, "name": cfg.name, "native_name": cfg.native_name,
                     "source": cfg.source, "source_url": cfg.source_url},
        "book": {"id": book.id, "title": book.title, "subtitle": book.subtitle,
                 "first": first, "last": last, "planned_last": book.last, "pilot": pilot},
        "built": date.today().isoformat(),
        "models": sorted(models),
        "stats": {"entries": len(entries), "sentences": n_sent, "concepts": len(in_range),
                  "reviews": n_rev, "ahead": n_ahead},
        "entries": out_entries,
        "appendix": appendix,
        "index": index,
        "grammar_index": gindex,
        "warnings": m.warnings,
    })


# ---------------------------------------------------------------------------
# Compile
# ---------------------------------------------------------------------------


def default_out(root: Path, book: Book, model: dict) -> Path:
    b = model["book"]
    suffix = f" (pilot {b['first']}-{b['last']})" if b["pilot"] else ""
    return root / f"{book.file}{suffix}.pdf"


def compile_pdf(model: dict, out: Path) -> None:
    try:
        import typst
    except ImportError as e:
        raise BookError("the 'typst' package is missing: uv pip install -r requirements.txt") from e
    CACHE.mkdir(parents=True, exist_ok=True)
    data = CACHE / f"{model['language']['code']}-{model['book']['id']}.json"
    data.write_text(json.dumps(model, ensure_ascii=False, indent=1), encoding="utf-8")
    try:
        pdf, warnings = typst.compile_with_warnings(
            str(TEMPLATE), root=str(REPO), font_paths=[str(FONTS)], ignore_system_fonts=True,
            sys_inputs={"data": "/" + data.relative_to(REPO).as_posix()})
    except typst.TypstError as e:
        hints = "".join(f"\n  hint: {h}" for h in (getattr(e, "hints", None) or []))
        raise BookError(f"typst: {e}{hints}") from e
    for w in warnings:
        print(f"typst warning: {w}", file=sys.stderr)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_bytes(pdf)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("language", help="language directory, e.g. german")
    ap.add_argument("--book", help="book id from language.toml [[books]] (default: first)")
    ap.add_argument("--to", type=int, help="cut the book's range at this order (pilot)")
    ap.add_argument("--out", type=Path, help="output PDF (default: <lang>/<file>.pdf)")
    args = ap.parse_args(argv)
    root = (REPO / args.language) if not Path(args.language).is_absolute() else Path(args.language)
    try:
        book = pick_book(load_config(root), args.book)
        model = build_model(root, book, args.to)
        out = args.out or default_out(root, book, model)
        compile_pdf(model, out)
    except (BookError, SchemaError, OSError) as e:
        print(f"error: {e}", file=sys.stderr)
        return 1
    s = model["stats"]
    print(f"{out}: {s['entries']} entries, {s['sentences']} sentences, "
          f"{s['concepts']} concepts, {len(model['warnings'])} warning(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
